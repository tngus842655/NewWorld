export type LegalKind = 'terms' | 'privacy';

export function renderLegal(root: HTMLElement, kind: LegalKind): void {
  const doc = kind === 'terms' ? TERMS : PRIVACY;
  root.replaceChildren(
    el('div.legal', {},
      el('div.legal-head', {},
        el('button.btn.btn-ghost.btn-sm', { onclick: () => { window.location.hash = ''; } }, '← 돌아가기'),
      ),
      el('h1.legal-title', {}, doc.title),
      doc.intro ? el('p.legal-intro', {}, doc.intro) : null,
      ...doc.sections.map((section) =>
        el('section.legal-sec', {},
          el('h2', {}, section.h),
          ...section.p.map((text) => el('p', {}, text)),
        )),
      el('div.legal-footer', {}, doc.footer),
    ),
  );
}
